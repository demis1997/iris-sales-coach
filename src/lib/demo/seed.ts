export function buildMarkers(callId: string): TimelineMarker[] {
  const a = analysisByCallId[callId];
  if (!a) return [];
  const markers: TimelineMarker[] = [];
  if (a.objections.length)
    markers.push({ callId, type: "objection", atSec: 110, label: "Objection" });
  if (
    a.topics.includes("pricing") ||
    a.objections.includes("pricing") ||
    a.objections.includes("spreads")
  ) {
    markers.push({ callId, type: "pricing", atSec: 55, label: "Pricing" });
  }
  if (a.competitors.length)
    markers.push({ callId, type: "competitor", atSec: 220, label: a.competitors[0] });
  if (a.sentiment === "Positive")
    markers.push({ callId, type: "positive", atSec: 330, label: "Positive" });
  if (a.sentiment === "Negative" || a.sentiment === "Mixed") {
    markers.push({ callId, type: "negative", atSec: 160, label: "Friction" });
  }
  if (a.interruptions >= 4)
    markers.push({ callId, type: "interruption", atSec: 180, label: "Interruptions" });
  if (a.nextSteps.length)
    markers.push({ callId, type: "next_step", atSec: 270, label: "Next step" });
  if (a.weaknesses.some((w) => /compliance|disclosure/i.test(w.text))) {
    markers.push({ callId, type: "compliance", atSec: 200, label: "Compliance gap" });
  }
  return markers;
}

