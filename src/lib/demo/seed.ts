function enrichDeal(d: DealBase): Deal {
  const health =
    d.riskLevel === "High"
      ? "Critical"
      : d.riskLevel === "Medium"
        ? "At risk"
        : d.stage === "Closed won"
          ? "Strong"
          : "Stable";
  const reasons: Deal["riskReasons"] =
    d.riskLevel === "High"
      ? ["Pricing hesitation", "Decision-maker absent"]
      : d.riskLevel === "Medium"
        ? ["Weak urgency", "No agreed next step"]
        : [];
  if (/compliance/i.test(d.nextStep)) reasons.push("Compliance concern");
  if (/competitor/i.test(d.nextStep)) reasons.push("Competitor evaluation");
  return {
    ...d,
    conversationHealth: health,
    lastInteraction: d.expectedCloseDate < "2026-07-20" ? "2026-07-10" : "2026-07-28",
    riskReasons: [...new Set(reasons)],
    stakeholders: d.riskLevel === "High" ? ["Champion"] : ["Champion", "Economic buyer"],
    crmSyncStatus: d.crmSource === "Pipedrive" ? "Needs mapping" : "Synced",
    irisRecommendation: d.nextStep,
  };
}

